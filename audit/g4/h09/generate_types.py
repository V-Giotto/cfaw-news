"""Generate TS wire types and runtime schemas from the H09 v2 contract export."""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SCHEMA = ROOT / "evals/intelligence_g4/schema/h09_v2"
TARGET = ROOT / "frontend/src/intelligence.generated.ts"
VALIDATION = ROOT / "frontend/src/intelligence.validation.generated.ts"
NAMES = ("StatusView", "DisabledStatus", "PersonaView", "PersonaWrite", "BriefingView", "BriefingWrite",
         "RunView", "CancelWrite", "InteractionView", "InteractionWrite", "MutationView", "EventDetailView", "SnapshotPage", "VisitView", "VisitWrite")


def generate():
    definitions = {}
    hashes = []
    for name in NAMES:
        raw = (SCHEMA / (name + ".schema.json")).read_bytes()
        hashes.append(hashlib.sha256(raw).hexdigest())
        schema = json.loads(raw)
        for key, value in {**schema.pop("$defs", {}), name: schema}.items():
            if key in definitions and definitions[key] != value:
                raise ValueError("schema name collision: " + key)
            definitions[key] = value

    def ts(value):
        if "$ref" in value:
            return value["$ref"].rsplit("/", 1)[-1]
        if "const" in value:
            return json.dumps(value["const"])
        if "enum" in value:
            return " | ".join(json.dumps(v) for v in value["enum"])
        if "anyOf" in value:
            return " | ".join(ts(v) for v in value["anyOf"])
        kind = value.get("type")
        if kind == "array":
            return "Array<" + ts(value["items"]) + ">"
        if kind == "object":
            if "properties" not in value:
                return "Record<string, " + ts(value.get("additionalProperties", {})) + ">"
            required = value.get("required", [])
            fields = [json.dumps(k) + (": " if k in required else "?: ") + ts(v)
                      for k, v in value["properties"].items()]
            return "{\n  " + ";\n  ".join(fields) + "\n}"
        return {"string": "string", "integer": "number", "number": "number",
                "boolean": "boolean", "null": "null"}.get(kind, "unknown")

    pin = hashlib.sha256("".join(hashes).encode()).hexdigest()
    return ("// Generated by audit/g4/h09/generate_types.py from g4-h09-contracts-v2.\n"
            "// Schema set SHA-256: " + pin + "\n// Wire shapes only; eligibility is never inferred from TS types.\n\n"
            + "\n\n".join("export type " + name + " = " + ts(value) for name, value in sorted(definitions.items()))
            + "\n"), ("// Generated from the same sealed schemas as intelligence.generated.ts.\n"
                         + "export const wireSchemas = " + json.dumps(definitions, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content, validation = generate()
    if args.check:
        assert TARGET.read_text(encoding="utf-8") == content, "G4_H09_TYPES_STALE"
        assert VALIDATION.read_text(encoding="utf-8") == validation, "G4_H09_VALIDATORS_STALE"
    else:
        TARGET.write_text(content, encoding="utf-8", newline="\n")
        VALIDATION.write_text(validation, encoding="utf-8", newline="\n")
    print("PASS: H09 wire types and runtime schemas")
